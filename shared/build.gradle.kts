// Turns contract/fixtures/*.json into a Kotlin map so commonTest reads them on every target without file access.
val generateContractFixtures = tasks.register("generateContractFixtures") {
    val fixturesDir = rootProject.layout.projectDirectory.dir("contract/fixtures")
    val outputDir = layout.buildDirectory.dir("generated/contractFixtures/commonTest/kotlin")
    inputs.dir(fixturesDir)
    outputs.dir(outputDir)
    doLast {
        val fixtures = fixturesDir.asFile.listFiles { file -> file.extension == "json" }.orEmpty().sortedBy { it.name }
        check(fixtures.isNotEmpty()) { "no fixtures in ${fixturesDir.asFile}" }
        val entries = fixtures.joinToString(",\n") { file ->
            val literal = file.readText()
                .replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
                .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
            "    \"${file.name}\" to \"$literal\""
        }
        // The task owns its output directory: files from earlier package names must not survive.
        outputDir.get().asFile.deleteRecursively()
        val target = outputDir.get().file("com/linux/recipes/contract/ContractFixtures.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(
            "// Generated by :shared:generateContractFixtures from contract/fixtures. Do not edit.\n" +
                "package com.linux.recipes.contract\n\n" +
                "val contractFixtures: Map<String, String> = mapOf(\n$entries,\n)\n",
        )
    }
}

// Client settings from gradle.properties, compiled into commonMain.
val generateAppConfig = tasks.register("generateAppConfig") {
    val baseUrl = providers.gradleProperty("API_BASE_URL")
    val values = listOf("GOOGLE_SERVER_CLIENT_ID", "REVENUECAT_ANDROID_KEY", "REVENUECAT_IOS_KEY", "TERMS_URL", "PRIVACY_URL")
        .associateWith { providers.gradleProperty(it).orElse("") }
    val outputDir = layout.buildDirectory.dir("generated/appConfig/commonMain/kotlin")
    inputs.property("baseUrl", baseUrl)
    values.forEach { (name, value) -> inputs.property(name, value) }
    outputs.dir(outputDir)
    doLast {
        val url = baseUrl.get()
        check(url.startsWith("https://") && !url.endsWith("/")) { "API_BASE_URL must be https and have no trailing slash: $url" }
        // RevenueCat's public SDK keys start with goog_ or appl_; a secret key (sk_) must never ship in the app.
        listOf("REVENUECAT_ANDROID_KEY", "REVENUECAT_IOS_KEY").forEach { name ->
            check(!values.getValue(name).get().startsWith("sk_")) { "$name is a RevenueCat secret key; use the public SDK key" }
        }
        // The task owns its output directory: files from earlier package names must not survive.
        outputDir.get().asFile.deleteRecursively()
        val target = outputDir.get().file("com/linux/recipes/AppConfig.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(
            "// Generated by :shared:generateAppConfig from gradle.properties. Do not edit.\n" +
                "package com.linux.recipes\n\n" +
                "object AppConfig {\n" +
                "    const val API_BASE_URL: String = \"$url\"\n" +
                values.entries.joinToString("") { (name, value) -> "    const val $name: String = \"${value.get()}\"\n" } +
                "}\n",
        )
    }
}

// The iOS bundle id lives in an xcconfig that Xcode reads before Gradle runs; keep it equal to APP_ID.
val verifyIosAppId = tasks.register("verifyIosAppId") {
    val appId = providers.gradleProperty("APP_ID")
    val xcconfig = rootProject.layout.projectDirectory.file("iosApp/Configuration/Config.xcconfig")
    inputs.property("appId", appId)
    inputs.file(xcconfig)
    doLast {
        val line = xcconfig.asFile.readLines().firstOrNull { it.startsWith("APP_ID=") }
        check(line == "APP_ID=${appId.get()}") {
            "iosApp/Configuration/Config.xcconfig has '$line', gradle.properties has APP_ID=${appId.get()}"
        }
    }
}

tasks.named("check") { dependsOn(verifyIosAppId) }

